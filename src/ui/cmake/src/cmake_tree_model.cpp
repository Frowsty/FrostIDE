#include "frost/ui/cmake/cmake_tree_model.hpp"

#include <QFont>
#include <QString>

#include <utility>

namespace frost::ui::cmake {

namespace {

QString toQString(std::string_view text) { return QString::fromUtf8(text.data(), static_cast<qsizetype>(text.size())); }

} // namespace

CMakeTreeModel::CMakeTreeModel(QObject* parent) : QAbstractItemModel(parent) {}

void CMakeTreeModel::setViewModel(std::shared_ptr<const project::CMakeViewModel> model) {
    beginResetModel();
    m_model = std::move(model);
    m_rows.clear();
    if (m_model) {
        const auto nodes = m_model->nodes();
        m_rows.assign(nodes.size(), 0);
        for (const project::CMakeViewNode& node : nodes) {
            for (std::size_t row = 0; row < node.children.size(); ++row) {
                m_rows[node.children[row]] = static_cast<int>(row);
            }
        }
    }
    endResetModel();
}

std::optional<std::size_t> CMakeTreeModel::nodeId(const QModelIndex& index) const {
    if (!index.isValid() || !m_model || index.internalId() >= m_model->nodes().size()) {
        return std::nullopt;
    }
    return static_cast<std::size_t>(index.internalId());
}

QModelIndex CMakeTreeModel::indexOfNode(std::size_t id) const {
    return createIndex(m_rows[id], 0, static_cast<quintptr>(id));
}

QModelIndex CMakeTreeModel::indexForKey(std::string_view key) const {
    if (!m_model) {
        return {};
    }
    const auto id = m_model->findKey(key);
    return id ? indexOfNode(*id) : QModelIndex();
}

QModelIndex CMakeTreeModel::index(int row, int column, const QModelIndex& parent) const {
    if (!m_model || column != 0 || row < 0) {
        return {};
    }
    if (!parent.isValid()) {
        return row == 0 ? indexOfNode(project::CMakeViewModel::root()) : QModelIndex();
    }
    const auto id = nodeId(parent);
    if (!id) {
        return {};
    }
    const auto& children = m_model->node(*id).children;
    if (static_cast<std::size_t>(row) >= children.size()) {
        return {};
    }
    return indexOfNode(children[static_cast<std::size_t>(row)]);
}

QModelIndex CMakeTreeModel::parent(const QModelIndex& child) const {
    const auto id = nodeId(child);
    if (!id) {
        return {};
    }
    const auto parentId = m_model->node(*id).parent;
    return parentId ? indexOfNode(*parentId) : QModelIndex();
}

int CMakeTreeModel::rowCount(const QModelIndex& parent) const {
    if (!m_model) {
        return 0;
    }
    if (!parent.isValid()) {
        return 1; // The project node.
    }
    if (parent.column() != 0) {
        return 0;
    }
    const auto id = nodeId(parent);
    return id ? static_cast<int>(m_model->node(*id).children.size()) : 0;
}

int CMakeTreeModel::columnCount(const QModelIndex& /*parent*/) const { return 1; }

QVariant CMakeTreeModel::data(const QModelIndex& index, int role) const {
    const auto id = nodeId(index);
    if (!id) {
        return {};
    }
    const project::CMakeViewNode& node = m_model->node(*id);
    switch (role) {
    case Qt::DisplayRole: return toQString(node.label);
    case Qt::ToolTipRole:
        if (node.path.empty()) {
            return {};
        }
        return node.generated ? QStringLiteral("%1 (generated by the build)").arg(toQString(node.path))
                              : toQString(node.path);
    case Qt::FontRole:
        if (node.generated) {
            QFont font;
            font.setItalic(true);
            return font;
        }
        return {};
    case PathRole: return toQString(node.path);
    case KindRole: return static_cast<int>(node.kind);
    case KeyRole: return toQString(node.key);
    case GeneratedRole: return node.generated;
    case TargetIndexRole: return node.target ? static_cast<int>(*node.target) : -1;
    default: return {};
    }
}

Qt::ItemFlags CMakeTreeModel::flags(const QModelIndex& index) const {
    return nodeId(index) ? Qt::ItemIsEnabled | Qt::ItemIsSelectable : Qt::NoItemFlags;
}

} // namespace frost::ui::cmake
