#ifdef _WIN32
const std::string kEngine = "C:\\engine";
#else
const std::string kEngine = "/engine";
#endif

// A reference shaped like the engine's ScriptApiDocs::GenerateMarkdown() output.
constexpr std::string_view kReference = R"(# Frost Scripting API

<!-- Generated by ScriptApiDocs::GenerateMarkdown() from the binding registrations. Do not edit by hand. -->

## Contents

- [Globals](#globals)

## Globals

| Member | Kind | Summary |
|---|---|---|
| `Wait(seconds: number)` | GlobalFunction | Resumes later. |
| `_VERSION: string` | GlobalValue | The Lua version ("Lua 5.4"). |
| `require(moduleName: string): any` | GlobalFunction | Loads a project module. |

### Wait

## Script class

### Script

#### Script:OnCreate

## Namespaces

Global tables of functions, properties and constants.

### Log

| Member | Kind | Summary |
|---|---|---|
| `Log.Info(message: string)` | Function | Logs. |

### Net

## Types

### Vec3

## Components

### Transform

## Enums

### Key

## Lua standard library

### os

### string
)";

std::string join(std::string_view relative) { return frost::io::joinPath(kEngine, relative).value(); }

void write(frost::io::MemFs& fs, std::string_view relative, std::string_view content) {
    const std::string path = join(relative);
    ASSERT_TRUE(fs.createDirectories(frost::io::parentPath(path)).has_value()) << path;
    ASSERT_TRUE(fs.writeFileAtomic(path, content).has_value()) << path;
}

TEST(FrostEngineLua, TheReferenceDeclaresGlobalsFromItsGlobalSectionsOnly) {
    auto api = frost::lang::parseFrostEngineScriptApi(kReference);
    ASSERT_TRUE(api.has_value()) << api.error().describe();
    EXPECT_EQ(api->globals,
              (std::vector<std::string>{"Key", "Log", "Net", "Vec3", "Wait", "_VERSION", "os", "require", "string"}));
    EXPECT_EQ(api->runtimeVersion, "Lua 5.4");
    // Script class names and components are not Lua globals.
    EXPECT_FALSE(std::ranges::contains(api->globals, std::string("Script")));
    EXPECT_FALSE(std::ranges::contains(api->globals, std::string("Transform")));

    const auto plain = frost::lang::parseFrostEngineScriptApi("# Notes\n\n## Globals\n\n### Wait\n");
    ASSERT_FALSE(plain.has_value()) << "a hand-written file is not the engine's reference";
    EXPECT_EQ(plain.error().code(), frost::ErrorCode::InvalidArgument);
    const auto empty = frost::lang::parseFrostEngineScriptApi(
        "<!-- Generated by ScriptApiDocs::GenerateMarkdown() -->\n## Components\n### Transform\n");
    EXPECT_FALSE(empty.has_value());
}

TEST(FrostEngineLua, AnEngineCheckoutFindsItsReferenceAndItsProjectsGeneratedDefinitions) {
    frost::io::MemFs fs(frost::systemClock());
    write(fs, "Docs/ScriptingAPI.md", kReference);
    write(fs, "Samples/Game/Game.frostproj", "{}");
    write(fs, "Samples/Game/.frost/lua-api/frost.lua", "---@meta\n");
    write(fs, "Samples/Bare/Bare.frostproj", "{}"); // No generated definitions: not listed.
    write(fs, "TestProject/TestProject.feproject", "version = 1\n");
    write(fs, "TestProject/.frost/lua-api/frost.lua", "---@meta\n");
    const auto profile = frost::lang::discoverFrostEngineLua(fs, kEngine);
    EXPECT_TRUE(profile.frostEngine);
    EXPECT_FALSE(profile.projectRoot);
    EXPECT_EQ(profile.reference, join("Docs/ScriptingAPI.md"));
    EXPECT_TRUE(profile.problem.empty()) << profile.problem;
    EXPECT_EQ(profile.library, (std::vector<std::string>{"Samples/Game/.frost/lua-api", "TestProject/.frost/lua-api"}));

    // A sample project inside the checkout finds the engine's reference two levels up.
    const auto sample = frost::lang::discoverFrostEngineLua(fs, join("Samples/Game"));
    EXPECT_TRUE(sample.frostEngine);
    EXPECT_TRUE(sample.projectRoot);
    EXPECT_EQ(sample.reference, join("Docs/ScriptingAPI.md"));
    EXPECT_EQ(sample.library, std::vector<std::string>{".frost/lua-api"});

    // A folder of the checkout that is no project is no FrostEngine workspace.
    write(fs, "Tools/readme.txt", "");
    EXPECT_FALSE(frost::lang::discoverFrostEngineLua(fs, join("Tools")).frostEngine);
}

TEST(FrostEngineLua, AProjectWithoutTheEngineReferenceClaimsNoGlobalsAndSaysWhy) {
    frost::io::MemFs fs(frost::systemClock());
    write(fs, "Game.frostproj", "{}");
    write(fs, "Docs/ScriptingAPI.md", "# Hand-written notes\n");
    const auto profile = frost::lang::discoverFrostEngineLua(fs, kEngine);
    EXPECT_TRUE(profile.frostEngine);
    EXPECT_TRUE(profile.api.globals.empty());
    EXPECT_NE(profile.problem.find("generated scripting reference"), std::string::npos) << profile.problem;
    const frost::lang::Json configuration = frost::lang::frostEngineLuaDefaults("Lua 5.3", profile);
    EXPECT_EQ(frost::lang::luaConfigurationSection(configuration, "Lua.diagnostics.globals").kind(),
              frost::lang::Json::Kind::Null);
    EXPECT_EQ(*frost::lang::luaConfigurationSection(configuration, "Lua.runtime.version").asString(), "Lua 5.3");
}

TEST(FrostEngineLua, TheConfigurationCarriesTheEnginesGlobalsVersionAndLibrary) {
    frost::io::MemFs fs(frost::systemClock());
    write(fs, "Docs/ScriptingAPI.md", kReference);
    write(fs, "Samples/Game/Game.frostproj", "{}");
    write(fs, "Samples/Game/.frost/lua-api/frost.lua", "---@meta\n");
    const auto profile = frost::lang::discoverFrostEngineLua(fs, kEngine);
    const frost::lang::Json configuration = frost::lang::frostEngineLuaDefaults("Lua 5.1", profile);
    const frost::lang::Json globals = frost::lang::luaConfigurationSection(configuration, "Lua.diagnostics.globals");
    ASSERT_TRUE(globals.isArray());
    std::vector<std::string> names;
    for (const frost::lang::Json& name : globals.items())
        names.emplace_back(*name.asString());
    EXPECT_EQ(names, profile.api.globals);
    // The engine's version wins over the setting; the generated definitions folders are the library.
    EXPECT_EQ(*frost::lang::luaConfigurationSection(configuration, "Lua.runtime.version").asString(), "Lua 5.4");
    const frost::lang::Json library = frost::lang::luaConfigurationSection(configuration, "Lua.workspace.library");
    ASSERT_TRUE(library.isArray());
    ASSERT_EQ(library.size(), 1U);
    EXPECT_EQ(*library.items()[0].asString(), "Samples/Game/.frost/lua-api");
    // The sandbox's builtins stay as luaDefaults(…, true) sets them.
    EXPECT_EQ(*frost::lang::luaConfigurationSection(configuration, "Lua.runtime.builtin.os").asString(), "disable");

    // Not a FrostEngine workspace: plain defaults.
    const frost::lang::Json plain = frost::lang::frostEngineLuaDefaults("Lua 5.1", {});
    EXPECT_EQ(plain.dump(), frost::lang::luaDefaults("Lua 5.1", false).dump());
}

